from palette import hx


def S(*rows):
    """Vult elke rij rechts aan tot 16 en het blok tot 16 rijen."""
    out = [r.ljust(16, ".") for r in rows]
    for r in out:
        if len(r) != 16:
            raise ValueError("rij te lang: %r" % r)
    while len(out) < 16:
        out.append("." * 16)
    if len(out) != 16:
        raise ValueError("te veel rijen: %d" % len(out))
    return out


